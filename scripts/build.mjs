// Builds dist/nevvyn-cards.js: the cards in one file. The Marketplace / HACS download only the
// file named in hacs.json, so everything the dashboard needs must live in that one file. Each card is
// wrapped in its own function so their top-level names cannot clash.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const FILES = ['control-panel-card.js', 'victron-ess-card.js', 'sun-day-card.js', 'lcars-data-field.js'];
const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;

let out = `/**\n * Nevvyn Cards ${version}: control-panel-card, victron-ess-card, sun-day-card and lcars-data-field in one file.\n * Generated by scripts/build.mjs from src/. Do not edit this file, edit the files in src/.\n */\n`;
for (const f of FILES) {
  out += `\n/* ===== ${f} ===== */\n(function () {\ntry {\n${readFileSync(join(root, 'src', f), 'utf8')}\n} catch (e) { console.error('nevvyn-cards: ${f} failed to start', e); }\n})();\n`;
}
mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist', 'nevvyn-cards.js'), out);
console.log(`built dist/nevvyn-cards.js (${out.length} bytes, v${version})`);
